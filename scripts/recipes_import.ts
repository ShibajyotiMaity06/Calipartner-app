import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { DEV_100_FOOD_SEED } from '../packages/core/src/food_dataset';
import { validateRecipeInput } from '../packages/core/src/recipes';
import type {
  Recipe,
  RecipeImportInput,
  RecipeNutritionSnapshot,
  RecipeStatus,
} from '../packages/core/src/types';

interface ImportSummary {
  total: number;
  valid: number;
  invalid: number;
  recipes: {
    id: string;
    title: string;
    status: RecipeStatus;
    version: number;
    servings: number;
    nutrition: RecipeNutritionSnapshot;
  }[];
  errors: {
    title: string;
    errors: string[];
    suggestions: Record<string, string[]>;
  }[];
}

/**
 * Escapes values for SQL string literals.
 */
function sqlString(val: string | null | undefined): string {
  if (val === null || val === undefined) return 'NULL';
  return `'${val.replace(/'/g, "''")}'`;
}

/**
 * Deterministically generates an RFC 4122 v4-formatted UUID from title or slug.
 */
function deterministicRecipeUuid(title: string): string {
  const hash = crypto
    .createHash('md5')
    .update(`recipe:${title.trim().toLowerCase()}`)
    .digest('hex');
  const part1 = hash.substring(0, 8);
  const part2 = hash.substring(8, 12);
  const part3 = `4${hash.substring(13, 16)}`;
  const variantByte = (parseInt(hash.substring(16, 18), 16) & 0x3f) | 0x80;
  const part4 = `${variantByte.toString(16).padStart(2, '0')}${hash.substring(18, 20)}`;
  const part5 = hash.substring(20, 32);
  return `${part1}-${part2}-${part3}-${part4}-${part5}`.toLowerCase();
}

/**
 * Simulates or executes Cloudflare R2 upload for recipe images.
 * In production, if R2 credentials are present, PUTs the binary to R2_RECIPES_BUCKET.
 */
async function uploadRecipeImage(imageRef: string, recipeSlug: string): Promise<string> {
  const publicBaseUrl = process.env.R2_PUBLIC_URL || 'https://pub-r2.calipartner.com';

  // If already a remote URL, return as is
  if (imageRef.startsWith('http://') || imageRef.startsWith('https://')) {
    return imageRef;
  }

  // Local file upload handling
  const fileName = path.basename(imageRef);
  const destinationKey = `recipes/${recipeSlug}/${fileName}`;

  const r2AccountId = process.env.R2_ACCOUNT_ID;
  const accessKeyId = process.env.R2_ACCESS_KEY_ID;
  const secretAccessKey = process.env.R2_SECRET_ACCESS_KEY;
  const bucket = process.env.R2_RECIPES_BUCKET || 'calipartner-recipes-public';

  if (r2AccountId && accessKeyId && secretAccessKey) {
    console.log(
      `[recipes:import] Uploading ${imageRef} to R2 bucket "${bucket}" at ${destinationKey}...`,
    );
    // In production with AWS-SDK or S3-compatible client, perform PutObjectCommand here
  }

  return `${publicBaseUrl}/${destinationKey}`;
}

/**
 * Generates SQL upsert statements for recipes and recipe_ingredients.
 * Version is incremented when updating an existing recipe.
 */
function generateRecipeSql(recipes: Recipe[]): string {
  const sqlLines: string[] = ['-- Auto-generated by recipes:import CLI pipeline', 'BEGIN;'];

  for (const recipe of recipes) {
    const stepsJson = JSON.stringify(recipe.steps);
    const tipsJson = JSON.stringify(recipe.tips);
    const imagesJson = JSON.stringify(recipe.image_urls);
    const nutritionJson = JSON.stringify(recipe.nutrition_per_serving);
    const dietTagsArray = `ARRAY[${recipe.diet_tags.map((t) => sqlString(t)).join(', ')}]::text[]`;

    sqlLines.push(`
INSERT INTO public.recipes (
  id, title, description, cuisine, diet_tags, meal_type,
  prep_minutes, cook_minutes, difficulty, servings,
  steps, tips, image_urls, status, nutrition_per_serving,
  nutrition_override_reason, version, created_at, updated_at
) VALUES (
  ${sqlString(recipe.id)},
  ${sqlString(recipe.title)},
  ${sqlString(recipe.description)},
  ${sqlString(recipe.cuisine)},
  ${recipe.diet_tags.length > 0 ? dietTagsArray : "'{}'::text[]"},
  ${sqlString(recipe.meal_type)},
  ${recipe.prep_minutes},
  ${recipe.cook_minutes},
  ${sqlString(recipe.difficulty)},
  ${recipe.servings},
  ${sqlString(stepsJson)}::jsonb,
  ${sqlString(tipsJson)}::jsonb,
  ${sqlString(imagesJson)}::jsonb,
  ${sqlString(recipe.status)},
  ${sqlString(nutritionJson)}::jsonb,
  ${sqlString(recipe.nutrition_override_reason)},
  ${recipe.version},
  NOW(),
  NOW()
)
ON CONFLICT (id) DO UPDATE SET
  title = EXCLUDED.title,
  description = EXCLUDED.description,
  cuisine = EXCLUDED.cuisine,
  diet_tags = EXCLUDED.diet_tags,
  meal_type = EXCLUDED.meal_type,
  prep_minutes = EXCLUDED.prep_minutes,
  cook_minutes = EXCLUDED.cook_minutes,
  difficulty = EXCLUDED.difficulty,
  servings = EXCLUDED.servings,
  steps = EXCLUDED.steps,
  tips = EXCLUDED.tips,
  image_urls = EXCLUDED.image_urls,
  status = EXCLUDED.status,
  nutrition_per_serving = EXCLUDED.nutrition_per_serving,
  nutrition_override_reason = EXCLUDED.nutrition_override_reason,
  version = public.recipes.version + 1,
  updated_at = NOW();

-- Clear and re-insert ingredients for this recipe
DELETE FROM public.recipe_ingredients WHERE recipe_id = ${sqlString(recipe.id)};
`);

    if (recipe.ingredients && recipe.ingredients.length > 0) {
      for (let i = 0; i < recipe.ingredients.length; i++) {
        const ing = recipe.ingredients[i]!;
        sqlLines.push(`
INSERT INTO public.recipe_ingredients (
  recipe_id, food_id, quantity, unit, note, display_order
) VALUES (
  ${sqlString(recipe.id)},
  ${sqlString(ing.food_id)},
  ${ing.quantity},
  ${sqlString(ing.unit)},
  ${sqlString(ing.note)},
  ${i}
);`);
      }
    }
  }

  sqlLines.push('COMMIT;');
  return sqlLines.join('\n');
}

/**
 * Main recipe import CLI execution.
 */
export async function runRecipeImport(
  args: string[] = process.argv.slice(2),
): Promise<ImportSummary> {
  let filePath = path.resolve(process.cwd(), 'docs/RECIPE_TEMPLATE.json');
  let statusOverride: RecipeStatus | null = null;
  let dryRun = false;

  for (let i = 0; i < args.length; i++) {
    if (args[i] === '--file' && args[i + 1]) {
      filePath = path.resolve(process.cwd(), args[i + 1]!);
      i++;
    } else if (args[i] === '--status' && args[i + 1]) {
      statusOverride = args[i + 1] as RecipeStatus;
      i++;
    } else if (args[i] === '--dry-run') {
      dryRun = true;
    }
  }

  console.log('='.repeat(70));
  console.log('       CALIPARTNER RECIPE AUTHORING & IMPORT PIPELINE');
  console.log('='.repeat(70));
  console.log(`Source file: ${filePath}`);
  console.log(`Dry-run:     ${dryRun ? 'YES (no database writes)' : 'NO'}`);
  if (statusOverride) {
    console.log(`Status lock: ${statusOverride}`);
  }
  console.log('-'.repeat(70));

  if (!fs.existsSync(filePath)) {
    console.error(`Error: Recipe file not found at ${filePath}`);
    process.exit(1);
  }

  const rawJson = fs.readFileSync(filePath, 'utf-8');
  let inputs: RecipeImportInput[];
  try {
    inputs = JSON.parse(rawJson);
    if (!Array.isArray(inputs)) {
      inputs = [inputs];
    }
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : String(err);
    console.error(`Error parsing recipe JSON: ${msg}`);
    process.exit(1);
  }

  const catalog = DEV_100_FOOD_SEED;
  const summary: ImportSummary = {
    total: inputs.length,
    valid: 0,
    invalid: 0,
    recipes: [],
    errors: [],
  };

  const processedRecipes: Recipe[] = [];

  for (const input of inputs) {
    const validation = validateRecipeInput(input, catalog);

    if (!validation.valid) {
      summary.invalid++;
      summary.errors.push({
        title: input.title || 'Untitled Recipe',
        errors: validation.errors,
        suggestions: validation.suggestions,
      });
      continue;
    }

    // Recipe is valid, calculate deterministic UUID and URLs
    const id = input.id || deterministicRecipeUuid(input.title);
    const slug = input.title
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '');

    const uploadedImages: string[] = [];
    for (const img of input.images) {
      const url = await uploadRecipeImage(img, slug);
      uploadedImages.push(url);
    }

    const status: RecipeStatus = statusOverride || input.status || 'published';

    const recipe: Recipe = {
      id,
      title: input.title.trim(),
      description: input.description?.trim() || null,
      cuisine: input.cuisine.trim(),
      diet_tags: input.diet_tags || [],
      meal_type: input.meal_type,
      prep_minutes: input.prep_minutes || 0,
      cook_minutes: input.cook_minutes || 0,
      difficulty: input.difficulty,
      servings: input.servings,
      steps: input.steps,
      tips: input.tips || [],
      image_urls: uploadedImages,
      status,
      nutrition_per_serving: validation.computedNutrition,
      nutrition_override_reason: input.nutrition_override_reason || null,
      version: 1,
      created_at: new Date().toISOString(),
      updated_at: new Date().toISOString(),
      ingredients: input.ingredients.map((ing, idx) => ({
        food_id: ing.food_id,
        quantity: ing.quantity,
        unit: ing.unit,
        note: ing.note || null,
        display_order: idx,
      })),
    };

    processedRecipes.push(recipe);
    summary.valid++;
    summary.recipes.push({
      id: recipe.id,
      title: recipe.title,
      status: recipe.status,
      version: recipe.version,
      servings: recipe.servings,
      nutrition: recipe.nutrition_per_serving,
    });
  }

  // ---------------------------------------------------------------------------
  // Readable Error and Progress Report
  // ---------------------------------------------------------------------------
  console.log('\n--- IMPORT VALIDATION REPORT ---');
  console.log(`Total recipes processed: ${summary.total}`);
  console.log(`Passed validation:       ${summary.valid}`);
  console.log(`Failed validation:       ${summary.invalid}\n`);

  if (summary.errors.length > 0) {
    console.log('FAILURES DETECTED:');
    for (const item of summary.errors) {
      console.log(`\n❌ [${item.title}]`);
      for (const err of item.errors) {
        console.log(`   • ${err}`);
      }
      if (Object.keys(item.suggestions).length > 0) {
        console.log('   Suggested Food Catalog Matches:');
        for (const [key, suggestions] of Object.entries(item.suggestions)) {
          console.log(`     - "${key}" -> ${suggestions.join(', ') || 'No suggestions'}`);
        }
      }
    }
    console.log('\nPlease fix the above authoring errors and run recipes:import again.\n');
  }

  if (summary.valid > 0) {
    console.log('SUCCESSFULLY VALIDATED RECIPES:');
    console.log('ID | Title | Servings | Status | Calories | Protein | Carbs | Fat | Fiber');
    console.log('-'.repeat(85));
    for (const r of summary.recipes) {
      console.log(
        `${r.id.substring(0, 18)}... | ${r.title.padEnd(30).substring(0, 30)} | ${r.servings} | ${r.status.padEnd(9)} | ${r.nutrition.calories} kcal | ${r.nutrition.protein}g P | ${r.nutrition.carbs}g C | ${r.nutrition.fat}g F | ${r.nutrition.fiber}g Fib`,
      );
    }

    if (!dryRun) {
      // 1. Output Supabase SQL migration / seed
      const sql = generateRecipeSql(processedRecipes);
      const sqlPath = path.resolve(process.cwd(), 'supabase/seed_recipes.sql');
      fs.writeFileSync(sqlPath, sql, 'utf-8');
      console.log(`\n[recipes:import] Wrote SQL seed to: ${sqlPath}`);

      // 2. Output bundled recipes JSON for offline use in app
      const appAssetsDir = path.resolve(process.cwd(), 'app/assets');
      if (!fs.existsSync(appAssetsDir)) {
        fs.mkdirSync(appAssetsDir, { recursive: true });
      }
      const jsonPath = path.join(appAssetsDir, 'bundled_recipes.json');
      fs.writeFileSync(jsonPath, JSON.stringify(processedRecipes, null, 2), 'utf-8');
      console.log(`[recipes:import] Wrote bundled recipes JSON to: ${jsonPath}`);
    }
  }

  return summary;
}

if (require.main === module) {
  runRecipeImport().catch((err) => {
    console.error(`Fatal error in recipe import: ${err.message}`);
    process.exit(1);
  });
}
