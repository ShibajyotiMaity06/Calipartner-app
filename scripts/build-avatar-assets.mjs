import sharp from 'sharp';
import prettier from 'prettier';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

const input = process.argv[2] ?? 'avatar/avatar';
const output = 'app/assets/avatar';
const seed = JSON.parse(await readFile('supabase/seed/avatar_catalog.json', 'utf8'));
await mkdir(output, { recursive: true });
const entries = {};
let bytes = 0;
async function emit(key, buffer) {
  const { width, height } = await sharp(buffer).metadata();
  if (!width || !height || Math.abs(width / height - 1536 / 2752) > 0.02)
    throw new Error(`Bad canvas ${key}: ${width}x${height}`);
  const name = key.replaceAll('/', '_').replace(/\.(jpg|png|webp)$/i, '');
  for (const [suffix, w] of [
    ['', 768],
    ['_preview', 256],
  ]) {
    const rendered = await sharp(buffer)
      .resize({ width: w })
      .webp({ quality: 86, alphaQuality: 100 })
      .toBuffer();
    const filename = `${name}${suffix}.webp`;
    await writeFile(path.join(output, filename), rendered);
    bytes += rendered.length;
    entries[key + suffix] = {
      file: filename,
      width: w,
      hash: createHash('sha256').update(rendered).digest('hex'),
    };
  }
}
// Flood only white connected to the canvas edge; interior whites (eyes) survive.
async function prepareBase(g, n) {
  const file = await readFile(path.join(input, `01_bases/form_${n}_${g}.jpg`));
  const { data, info } = await sharp(file)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { width: w, height: h } = info;
  const seen = new Uint8Array(w * h);
  const queue = new Int32Array(w * h);
  let head = 0,
    tail = 0;
  function visit(i) {
    if (i < 0 || i >= w * h || seen[i]) return;
    const o = i * 4;
    if (Math.min(data[o], data[o + 1], data[o + 2]) < 225) return;
    seen[i] = 1;
    queue[tail++] = i;
  }
  for (let x = 0; x < w; x++) {
    visit(x);
    visit((h - 1) * w + x);
  }
  for (let y = 0; y < h; y++) {
    visit(y * w);
    visit(y * w + w - 1);
  }
  while (head < tail) {
    const i = queue[head++];
    if (i % w) visit(i - 1);
    if (i % w < w - 1) visit(i + 1);
    visit(i - w);
    visit(i + w);
  }
  const skin = Buffer.alloc(data.length);
  for (let i = 0; i < w * h; i++) {
    const o = i * 4;
    const r = data[o],
      green = data[o + 1],
      b = data[o + 2];
    if (seen[i]) data[o + 3] = 0;
    // Warm skin segmentation excludes grayscale garments and dark facial features.
    if (!seen[i] && r > 90 && r > green * 1.08 && green > b * 1.06 && r - b > 28) {
      const shade = Math.min(255, Math.round((r + green + b) / 3));
      skin[o] = skin[o + 1] = skin[o + 2] = shade;
      skin[o + 3] = data[o + 3];
    }
  }
  await emit(`base_${g}_form${n}`, await sharp(data, { raw: info }).png().toBuffer());
  await emit(`skinmask_${g}_form${n}`, await sharp(skin, { raw: info }).png().toBuffer());
}
for (const g of ['m', 'f']) for (const n of [1, 2, 3]) await prepareBase(g, n);
const files = [...new Set(seed.products.flatMap((p) => Object.values(p.assets)))];
for (const file of files) {
  const source = await readFile(path.join(input, file));
  const meta = await sharp(source).metadata();
  if (file.includes('/auras/') && !meta.hasAlpha) {
    const { data, info } = await sharp(source)
      .ensureAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    for (let o = 0; o < data.length; o += 4) {
      const maximum = Math.max(data[o], data[o + 1], data[o + 2]);
      data[o + 3] = maximum;
      if (maximum)
        for (let c = 0; c < 3; c++) data[o + c] = Math.round((data[o + c] * 255) / maximum);
    }
    await emit(file, await sharp(data, { raw: info }).png().toBuffer());
  } else {
    if (!file.includes('/backdrops/') && !meta.hasAlpha) throw new Error(`Missing alpha: ${file}`);
    await emit(file, source);
  }
}
await writeFile(`${output}/manifest.json`, JSON.stringify(entries, null, 2) + '\n');
await writeFile(
  'app/src/components/avatar/assets.generated.ts',
  await prettier.format(
    `/* eslint-disable @typescript-eslint/no-require-imports */\n// Generated by scripts/build-avatar-assets.mjs. Metro requires static asset paths.\nexport const avatarAssets: Record<string, number> = {\n${Object.entries(
      entries,
    )
      .map(([key, v]) => `  ${JSON.stringify(key)}: require('../../../assets/avatar/${v.file}'),`)
      .join('\n')}\n};\n`,
    {
      ...(await prettier.resolveConfig('app/src/components/avatar/assets.generated.ts')),
      parser: 'typescript',
    },
  ),
);
console.log(
  `Avatar assets: ${Object.keys(entries).length} variants validated; ${(bytes / 1024 / 1024).toFixed(2)} MiB. Auto skin masks require visual review.`,
);
