import sharp from 'sharp';
import { readFile, writeFile } from 'node:fs/promises';
import prettier from 'prettier';

// Read alpha only. Keep the original artwork and layer coordinates untouched.
const manifest = JSON.parse(await readFile('app/assets/avatar/manifest.json', 'utf8'));
const bounds = {};
for (const [key, asset] of Object.entries(manifest)) {
  if (!key.startsWith('03_items_clean/') || key.endsWith('_preview')) continue;
  const { data, info } = await sharp(`app/assets/avatar/${asset.file}`)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  let left = info.width,
    top = info.height,
    right = 0,
    bottom = 0;
  for (let y = 0; y < info.height; y++)
    for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] < 24) continue;
      left = Math.min(left, x);
      right = Math.max(right, x);
      top = Math.min(top, y);
      bottom = Math.max(bottom, y);
    }
  if (right <= left || bottom <= top) throw new Error(`Empty item: ${key}`);
  const padding = Math.ceil(Math.max(right - left, bottom - top) * 0.08);
  const sx = 1536 / info.width,
    sy = 2752 / info.height;
  bounds[key] = [
    Math.floor((left - padding) * sx),
    Math.floor((top - padding) * sy),
    Math.ceil((right - left + padding * 2) * sx),
    Math.ceil((bottom - top + padding * 2) * sy),
  ].join(' ');
}
const target = 'app/src/components/avatar/thumbnailBounds.generated.ts';
await writeFile(
  target,
  await prettier.format(
    `// Generated by scripts/avatar_thumbnail_bounds.mjs from item alpha bounds.\nexport const thumbnailBounds: Record<string, string> = ${JSON.stringify(bounds)};\n`,
    { ...(await prettier.resolveConfig(target)), parser: 'typescript' },
  ),
);
console.log(`Item thumbnail bounds: ${Object.keys(bounds).length} layers validated`);
